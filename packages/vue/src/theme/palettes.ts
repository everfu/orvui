export const THEME_LIST = (Object.keys(THEMES) as ColorTheme[]).map(id => ({ id, name: THEMES[id].name, swatch: THEMES[id].swatch }));

const links: ReadonlyArray<readonly [string, string]> = [
  ["--card-foreground", "--foreground"], ["--popover", "--card"],
  ["--popover-foreground", "--foreground"], ["--secondary", "--card"],
  ["--secondary-foreground", "--foreground"], ["--muted", "--card"],
  ["--accent-foreground", "--accent-fg"], ["--destructive", "--danger"],
  ["--input", "--border"], ["--ring", "--border-strong"],
];
function declarations(selector: string, values: ThemeVars) {
  const resolved = new Map<string, string>();
  for (const name of Object.keys(values)) resolved.set(name, values[name]);
  for (const [name, target] of links) {
    if (Object.hasOwn(values, name) && values[name] === values[target]) resolved.set(name, `var(${target})`);
  }
  const lines = [selector + " {"];
  resolved.forEach((value, name) => lines.push(`  ${name}: ${value};`));
  lines.push("}");
  return lines.join("\n");
}
export function themeExportCss(id: ColorTheme): string {
  const selected = THEMES[id];
  return [declarations(":root", selected.light), declarations(".dark", selected.dark)].join("\n\n");
}
export function themesStylesheet(): string {
  const rules: string[] = [];
  for (const item of THEME_LIST) {
    if (item.id === "default") continue;
    const palette = THEMES[item.id];
    const selector = `[data-theme="${item.id}"]`;
    rules.push(declarations(selector, palette.light) + "\n" + declarations(".dark" + selector, palette.dark));
  }
  return rules.join("\n\n");
}
